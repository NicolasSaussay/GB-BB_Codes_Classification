// =======================================================================
// GB(4,4) classification: one representative per [[2n, k, d]]
//
// Classifies Generalized Bicycle (GB) quantum CSS codes [[2n, k, d]] built from
// two weight-4 polynomials a(X), b(X) over GF(2)[X]/(X^n - 1).
//
// Method:
//   1. One representative per equivalence class of pairs (a, b) (shifts,
//      multipliers X -> X^m, swap a <-> b), via canonical integer bitmasks.
//   2. Minimum distance with a fast path through MinimumWeight(Ker H_X).
//   3. Interactive mode, or parallel batch mode (slices of the representative list).
//
// Usage:
//   Interactive:  magma -b n:=10 gb44_one_representative.m
//   Batch slice:  magma -b n:=10 tranche:=0 nb:=4 gb44_one_representative.m
//   Parameters:   n   = length of each circulant block (code length 2n)
//                 tranche = index of the slice to process (0 .. nb-1); omit for interactive mode
//                 nb  = total number of slices
//
// Output:
//   Interactive: list of parameters (2n, k, d), each with one example pair (A, B).
//   Batch: lines "PARAM 2n k d ; A = ... ; B = ..." (lines starting with "#" are information).
// =======================================================================

// =======================================================================
// Classification of GB codes [[2n, k, d]] with a, b of Hamming weight 4
// =======================================================================


R<X> := PolynomialRing(GF(2));


// -----------------------------------------------------------------------
// CirculantMatrix(l, p)
//
// l×l circulant matrix over GF(2) whose FIRST COLUMN is p
// (padded with zeros): entry (i,j) = p[1 + (i - j) mod l].
// This is the matrix of multiplication by p(X) in GF(2)[X]/(X^l - 1).
// (Same matrix as the previous version; only the comment changes.)
// -----------------------------------------------------------------------
CirculantMatrix := function(l, p)
    if #p gt l then
        error "rows too large";
    end if;
    p := p cat [ GF(2)!0 : i in [1..l - #p] ];
    return Matrix(GF(2), [ [ p[1 + (i - j) mod l] : j in [1..l] ] : i in [1..l] ]);
end function;


// -----------------------------------------------------------------------
// PolDeSupport(S, n) : polynomial in GF(2)[X] with support S ⊂ {0..n-1}
// -----------------------------------------------------------------------
PolDeSupport := func< S, n | R![ i in S select 1 else 0 : i in [0..n-1] ] >;


// -----------------------------------------------------------------------
// definis_liste_supports_de_poids_4(n)
// All supports {0, aa, bb, cc} with 0 < aa < bb < cc < n
// -----------------------------------------------------------------------
definis_liste_supports_de_poids_4 := function(n)
    liste := [];
    for aa := 1 to n - 3 do
        for bb := aa + 1 to n - 2 do
            for cc := bb + 1 to n - 1 do
                Append(~liste, {0, aa, bb, cc});
            end for;
        end for;
    end for;
    return liste;
end function;


// -----------------------------------------------------------------------
// EntiersPremiersAvecN(n) : (Z/nZ)* seen as a list of integers from [1..n-1]
// Contains 1 (identity) and n-1 (involution Tilde X -> X^{-1}).
// -----------------------------------------------------------------------
EntiersPremiersAvecN := func< n | [ m : m in [1..n-1] | GCD(m, n) eq 1 ] >;


// =======================================================================
//  PART 1: EQUIVALENCE CLASS REPRESENTATIVES
// =======================================================================

// Integer key of a support S ⊂ {0..n-1}: bitmask sum 2^s
Cle := func< S | &+[ 2^s : s in S ] >;

// Support associated with an integer key
SupportDeCle := function(k)
    bits := Intseq(k, 2);
    return { i - 1 : i in [1..#bits] | bits[i] eq 1 };
end function;

// Canonical form under X^i shifts: min of translates containing 0
CanonShift := function(S, n)
    return Min([ Cle({ (s - t) mod n : s in S }) : t in S ]);
end function;


// -----------------------------------------------------------------------
// representants_des_couples_v2(n)
//
// One representative per orbit of pairs (a, b) under the group generated by:
//   - independent shifts a -> X^i a, b -> X^j b
//   - simultaneous multipliers X -> X^m (m coprime to n),
//     which includes Tilde (m = n - 1)
//   - swap a <-> b
//
// Principle (ordered generation): a pair of shift classes (ka <= kb)
// is encoded by the integer ka * 2^n + kb; a pair is kept
// iff no multiplier produces a strictly smaller key.
// Each orbit thus has exactly one representative (the one with minimum key),
// without storing any orbits.
//
// Output: list of pairs <SupportA, SupportB>
// -----------------------------------------------------------------------
representants_des_couples_v2 := function(n)
    unites := EntiersPremiersAvecN(n);
    N := 2^n;

    // One support per shift class (approximately C(n-1,3)/4 classes)
    cles := Sort(SetToSequence(
                { CanonShift(S, n) : S in definis_liste_supports_de_poids_4(n) }));
    supports := [ SupportDeCle(k) : k in cles ];

    // T[i][t] = shift class of X -> X^{m_t} applied to supports[i]
    T := [ [ CanonShift({ (m*s) mod n : s in S }, n) : m in unites ] : S in supports ];

    res := [];
    for i in [1..#cles] do
        for j in [i..#cles] do
            c0 := cles[i] * N + cles[j];
            estRep := true;
            for t in [1..#unites] do
                ka := T[i][t];
                kb := T[j][t];
                c  := ka le kb select ka * N + kb else kb * N + ka;
                if c lt c0 then
                    estRep := false;
                    break;
                end if;
            end for;
            if estRep then
                Append(~res, <supports[i], supports[j]>);
            end if;
        end for;
    end for;

    return res;
end function;


// =======================================================================
//  PART 2: MINIMUM DISTANCE
// =======================================================================

// -----------------------------------------------------------------------
// DistanceGB(n, PolA, PolB)
//
// d = min wt( Ker(H_X) \ Im(H_Z^T) )   (d_X = d_Z for a GB)
//
// C = Ker(H_X), D = Im(H_Z^T), D ⊂ C.
//   - d >= d0 := MinimumWeight(C)
//   - D has no non-zero words of weight < d0 (since D ⊂ C)
//   - if MinimumWeight(D) > d0, the weight d0 words of C are
//     logicals, so d = d0 (fast path)
//   - otherwise, count words of weight d in C and D starting from d0
//
// Output: d, rapide   (rapide = true if the fast path was sufficient)
// -----------------------------------------------------------------------
DistanceGB := function(n, PolA, PolB)
    A  := CirculantMatrix(n, Coefficients(PolA));
    B  := CirculantMatrix(n, Coefficients(PolB));
    HX := HorizontalJoin(A, B);
    HZ := HorizontalJoin(Transpose(B), Transpose(A));

    C := Dual(LinearCode(HX));   // Ker(H_X)
    D := LinearCode(HZ);         // Im(H_Z^T), subcode of C

    d0 := MinimumWeight(C);

    // Fast path
    if MinimumWeight(D) gt d0 then
        return d0, true;
    end if;

    // Slow path: counting starting from d0 (instead of 2)
    d := d0;
    while d le 2*n do
        nD := #Words(D, d : Method := "Zimmermann");
        nC := #Words(C, d : Method := "Zimmermann", NumWords := nD + 1);
        if nC ne nD then
            return d, false;
        end if;
        d +:= 1;
    end while;

    return 0, false; // does not happen: k >= 2 for weight 4 polynomials
end function;



// =======================================================================
//  PART 3: COMPUTATION OF PARAMETERS
// =======================================================================

// -----------------------------------------------------------------------
// calcul_parametres_v2(n, reps : tranche, nb_tranches)
//
// Processes representatives with index idx ≡ tranche (mod nb_tranches).
//
// Output:
//   - params     : associative array <2n, k, d>  ->  a representative pair
//   - nb_traites : number of representatives processed in this slice
//   - nb_rapides : number of distances obtained via the fast path
// -----------------------------------------------------------------------
calcul_parametres_v2 := function(n, reps : tranche := 0, nb_tranches := 1)
    diviseur := X^n - 1;
    params := AssociativeArray();
    nb_traites := 0;
    nb_rapides := 0;

    for idx in [1..#reps] do
        if (idx mod nb_tranches) ne tranche then
            continue;
        end if;

        couple := reps[idx];
        PolA := PolDeSupport(couple[1], n);
        PolB := PolDeSupport(couple[2], n);

        // (X+1) divides any even-weight polynomial, so k >= 2 always
        k := 2 * Degree(GCD(diviseur, GCD(PolA, PolB)));
        d, rapide := DistanceGB(n, PolA, PolB);

        nb_traites +:= 1;
        if rapide then
            nb_rapides +:= 1;
        end if;

        cle := <2*n, k, d>;
        if not IsDefined(params, cle) then
            params[cle] := couple;
        end if;
    end for;

    return params, nb_traites, nb_rapides;
end function;


// Sorting triplets by k then by d
TriParametres := func< L | Sort(L, func< a, b | a[2] ne b[2] select a[2] - b[2]
                                                 else a[3] - b[3] >) >;



// =======================================================================
//  MAIN PROGRAM
// =======================================================================

// Command-line variables arrive as strings
EnEntier := func< x | Type(x) eq MonStgElt select StringToInteger(x) else x >;


if not assigned n then
    n := 10;
end if;
if not assigned tranche then
    tranche := "-1";          // "-1" = no slice => interactive mode
end if;
if not assigned nb then
    nb := "1";
end if;

n                 := EnEntier(n);
num_tranche       := EnEntier(tranche);
nb_tranches_total := EnEntier(nb);

mode_batch := num_tranche ge 0;

if mode_batch then
    SetNthreads(1);    // one thread per process: parallelism is between processes
else
    num_tranche       := 0;
    nb_tranches_total := 1;
    SetNthreads(16);
end if;

// --- Phase 1: representatives
t0 := Realtime();
reps := representants_des_couples_v2(n);
t_reps := Realtime(t0);

// --- Phase 2: distances
t0 := Realtime();
params, nb_traites, nb_rapides := calcul_parametres_v2(n, reps
                                    : tranche := num_tranche,
                                      nb_tranches := nb_tranches_total);
t_dist := Realtime(t0);

cles_triees := TriParametres([ c : c in Keys(params) ]);

if mode_batch then
    // Lines "#" = information; lines "PARAM" = results
    printf "# n = %o, slice %o / %o\n", n, num_tranche, nb_tranches_total;
    printf "# representatives (total): %o, processed here: %o\n", #reps, nb_traites;
    printf "# fast path: %o / %o\n", nb_rapides, nb_traites;
    printf "# representatives time: %o s, distances time: %o s\n", t_reps, t_dist;
    for p in cles_triees do
        c := params[p];
        printf "PARAM %o %o %o ; A = %o ; B = %o\n",
               p[1], p[2], p[3], PolDeSupport(c[1], n), PolDeSupport(c[2], n);
    end for;
    quit;
else
    printf "\n ----------- FOR n = %o --------------\n\n", n;
    printf "Representatives: %o (computed in %o s)\n", #reps, t_reps;
    printf "Distances      : %o s, fast path for %o / %o codes\n\n",
           t_dist, nb_rapides, nb_traites;
    print "Here is the list of all possible parameters (with an example):";
    print "";
    for p in cles_triees do
        c := params[p];
        printf "- (%o, %o, %o)   ex.: A = %o,  B = %o\n",
               p[1], p[2], p[3], PolDeSupport(c[1], n), PolDeSupport(c[2], n);
    end for;
    print "";
end if;
