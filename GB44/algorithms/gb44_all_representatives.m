// =======================================================================
// GB(4,4) classification: all non-equivalent representatives per [[2n, k, d]]
//
// Classifies Generalized Bicycle (GB) quantum CSS codes [[2n, k, d]] built from
// two weight-4 polynomials a(X), b(X) over GF(2)[X]/(X^n - 1).
//
// Method:
//   1. One representative per equivalence class of pairs (a, b) (shifts,
//      multipliers X -> X^m, swap a <-> b), via canonical integer bitmasks.
//   2. Minimum distance with a fast path through MinimumWeight(Ker H_X).
//   3. Interactive mode, or parallel batch mode (slices of the representative list).
//
// Usage:
//   Interactive:  magma -b n:=10 gb44_all_representatives.m
//   Batch slice:  magma -b n:=10 slice:=0 nb:=4 gb44_all_representatives.m
//   Parameters:   n   = length of each circulant block (code length 2n)
//                 slice = index of the slice to process (0 .. nb-1); omit for interactive mode
//                 nb  = total number of slices
//
// Output:
//   Interactive: list of parameters (2n, k, d) with all representative pairs (A, B).
//   Batch: lines "PARAM 2n k d ; A = ... ; B = ..." (lines starting with "#" are information).
// =======================================================================

// =======================================================================
// Classification of [[2n, k, d]] GB codes with Hamming weight 4 a, b
// =======================================================================

R<X> := PolynomialRing(GF(2));


// -----------------------------------------------------------------------
// CirculantMatrix(l, p)
//
// l x l circulant matrix over GF(2) whose FIRST COLUMN is p
// (padded with zeros): entry (i,j) = p[1 + (i - j) mod l].
// This is the matrix of multiplication by p(X) in GF(2)[X]/(X^l - 1).
// (Same matrix as previous version; only the comment changes.)
// -----------------------------------------------------------------------
CirculantMatrix := function(l, p)
    if #p gt l then
        error "rows too large";
    end if;
    p := p cat [ GF(2)!0 : i in [1..l - #p] ];
    return Matrix(GF(2), [ [ p[1 + (i - j) mod l] : j in [1..l] ] : i in [1..l] ]);
end function;


// -----------------------------------------------------------------------
// SupportPolynomial(S, n) : polynomial in GF(2)[X] with support S subset {0..n-1}
// -----------------------------------------------------------------------
SupportPolynomial := func< S, n | R![ i in S select 1 else 0 : i in [0..n-1] ] >;


// -----------------------------------------------------------------------
// define_weight_4_support_list(n)
// All supports {0, aa, bb, cc} with 0 < aa < bb < cc < n
// -----------------------------------------------------------------------
define_weight_4_support_list := function(n)
    list := [];
    for aa := 1 to n - 3 do
        for bb := aa + 1 to n - 2 do
            for cc := bb + 1 to n - 1 do
                Append(~list, {0, aa, bb, cc});
            end for;
        end for;
    end for;
    return list;
end function;


// -----------------------------------------------------------------------
// CoprimeIntegersToN(n) : (Z/nZ)* viewed as a list of integers from [1..n-1]
// Contains 1 (identity) and n-1 (Tilde involution X -> X^{-1}).
// -----------------------------------------------------------------------
CoprimeIntegersToN := func< n | [ m : m in [1..n-1] | GCD(m, n) eq 1 ] >;


// =======================================================================
//  PART 1: EQUIVALENCE CLASS REPRESENTATIVES
// =======================================================================

// Integer key of a support S subset {0..n-1} : bitmask sum 2^s
Key := func< S | &+[ 2^s : s in S ] >;

// Support associated with an integer key
SupportFromKey := function(k)
    bits := Intseq(k, 2);
    return { i - 1 : i in [1..#bits] | bits[i] eq 1 };
end function;

// Canonical form under shifts X^i : min of translates containing 0
CanonicalShift := function(S, n)
    return Min([ Key({ (s - t) mod n : s in S }) : t in S ]);
end function;


// -----------------------------------------------------------------------
// couple_representatives_v2(n)
//
// One representative per pair orbit (a, b) under the group generated by:
//   - independent shifts  a -> X^i a,  b -> X^j b
//   - simultaneous multipliers X -> X^m (m coprime to n),
//     which includes Tilde (m = n - 1)
//   - swap a <-> b
//
// Principle (ordered generation): a pair of shift classes (ka <= kb)
// is encoded by the integer ka * 2^n + kb; a pair is kept
// iff no multiplier produces a strictly smaller key.
// Each orbit thus has exactly one representative (the one with minimal key),
// without storing any orbits.
//
// Output: list of pairs <SupportA, SupportB>
// -----------------------------------------------------------------------
couple_representatives_v2 := function(n)
    units := CoprimeIntegersToN(n);
    N := 2^n;

    // One support per shift class (roughly C(n-1,3)/4 classes)
    keys := Sort(SetToSequence(
                { CanonicalShift(S, n) : S in define_weight_4_support_list(n) }));
    supports := [ SupportFromKey(k) : k in keys ];

    // T[i][t] = shift class of X -> X^{m_t} applied to supports[i]
    T := [ [ CanonicalShift({ (m*s) mod n : s in S }, n) : m in units ] : S in supports ];

    res := [];
    for i in [1..#keys] do
        for j in [i..#keys] do
            c0 := keys[i] * N + keys[j];
            isRep := true;
            for t in [1..#units] do
                ka := T[i][t];
                kb := T[j][t];
                c  := ka le kb select ka * N + kb else kb * N + ka;
                if c lt c0 then
                    isRep := false;
                    break;
                end if;
            end for;
            if isRep then
                Append(~res, <supports[i], supports[j]>);
            end if;
        end for;
    end for;

    return res;
end function;


// =======================================================================
//  PART 2: MINIMUM DISTANCE
// =======================================================================

// -----------------------------------------------------------------------
// DistanceGB(n, PolA, PolB)
//
// d = min wt( Ker(H_X) \ Im(H_Z^T) )   (d_X = d_Z for a GB code)
//
// C = Ker(H_X), D = Im(H_Z^T), D subset C.
//   - d >= d0 := MinimumWeight(C)
//   - D contains no non-zero words of weight < d0 (since D subset C)
//   - if MinimumWeight(D) > d0, the weight-d0 words of C are
//     logicals, so d = d0 (fast path)
//   - otherwise, count words of weight d in C and D starting from d0
//
// Output: d, fast   (fast = true if the fast path was sufficient)
// -----------------------------------------------------------------------
DistanceGB := function(n, PolA, PolB)
    A  := CirculantMatrix(n, Coefficients(PolA));
    B  := CirculantMatrix(n, Coefficients(PolB));
    HX := HorizontalJoin(A, B);
    HZ := HorizontalJoin(Transpose(B), Transpose(A));

    C := Dual(LinearCode(HX));   // Ker(H_X)
    D := LinearCode(HZ);         // Im(H_Z^T), subcode of C

    d0 := MinimumWeight(C);

    // Fast path
    if MinimumWeight(D) gt d0 then
        return d0, true;
    end if;

    // Slow path: counting starting from d0 (instead of 2)
    d := d0;
    while d le 2*n do
        nD := #Words(D, d : Method := "Zimmermann");
        nC := #Words(C, d : Method := "Zimmermann", NumWords := nD + 1);
        if nC ne nD then
            return d, false;
        end if;
        d +:= 1;
    end while;

    return 0, false; // should not happen: k >= 2 for weight 4 polynomials
end function;




// =======================================================================
//  PART 3: COMPUTATION OF PARAMETERS
// =======================================================================

// -----------------------------------------------------------------------
// compute_parameters_v2(n, reps : slice, nb_slices)
//
// Processes representatives with index idx ≡ slice (mod nb_slices).
//
// Output:
//   - params     : associative array <2n, k, d>  ->  list of ALL representative
//                  pairs (non-equivalent under G) having these parameters
//   - nb_processed : number of representatives processed in this slice
//   - nb_fast      : number of distances obtained via the fast path
// -----------------------------------------------------------------------
compute_parameters_v2 := function(n, reps : slice := 0, nb_slices := 1)
    divisor := X^n - 1;
    params := AssociativeArray();
    nb_processed := 0;
    nb_fast := 0;

    for idx in [1..#reps] do
        if (idx mod nb_slices) ne slice then
            continue;
        end if;

        couple := reps[idx];
        PolA := SupportPolynomial(couple[1], n);
        PolB := SupportPolynomial(couple[2], n);

        // (X+1) divides any even weight polynomial, so k >= 2 always
        k := 2 * Degree(GCD(divisor, GCD(PolA, PolB)));
        d, fast := DistanceGB(n, PolA, PolB);

        nb_processed +:= 1;
        if fast then
            nb_fast +:= 1;
        end if;

        key := <2*n, k, d>;
        if IsDefined(params, key) then
            L := params[key];
            Append(~L, couple);
            params[key] := L;
        else
            params[key] := [ couple ];
        end if;
    end for;

    return params, nb_processed, nb_fast;
end function;


// Sort triplets by k then by d
SortParameters := func< L | Sort(L, func< a, b | a[2] ne b[2] select a[2] - b[2]
                                                 else a[3] - b[3] >) >;




// =======================================================================
//  MAIN PROGRAM
// =======================================================================

// Command-line arguments arrive as strings
AsInteger := func< x | Type(x) eq MonStgElt select StringToInteger(x) else x >;

// Magma checks identifier existence at compilation of each instruction,
// even in a non-executed branch. We therefore declare default values
// WITHOUT overwriting those passed via "magma -b n:=... ".
// (Assignment inside an if does not reference the identifier: it compiles.)
if not assigned n then
    n := 10;
end if;
if not assigned slice then
    slice := "-1";          // "-1" = no slice => interactive mode
end if;
if not assigned nb then
    nb := "1";
end if;

n               := AsInteger(n);
num_slice       := AsInteger(slice);
nb_slices_total := AsInteger(nb);

batch_mode := num_slice ge 0;

if batch_mode then
    SetNthreads(1);    // one thread per process: parallelism is between processes
else
    num_slice       := 0;
    nb_slices_total := 1;
    SetNthreads(16);
end if;

// --- Phase 1: representatives
t0 := Realtime();
reps := couple_representatives_v2(n);
t_reps := Realtime(t0);

// --- Phase 2: distances
t0 := Realtime();
params, nb_processed, nb_fast := compute_parameters_v2(n, reps
                                    : slice := num_slice,
                                      nb_slices := nb_slices_total);
t_dist := Realtime(t0);

sorted_keys := SortParameters([ c : c in Keys(params) ]);

if batch_mode then
    // "#" lines = information; "PARAM" lines = results
    printf "# n = %o, slice %o / %o\n", n, num_slice, nb_slices_total;
    printf "# representatives (total) : %o, processed here : %o\n", #reps, nb_processed;
    printf "# fast path : %o / %o\n", nb_fast, nb_processed;
    printf "# representatives time : %o s, distances time : %o s\n", t_reps, t_dist;
    for p in sorted_keys do
        for c in params[p] do
            printf "PARAM %o %o %o ; A = %o ; B = %o\n",
                   p[1], p[2], p[3], SupportPolynomial(c[1], n), SupportPolynomial(c[2], n);
        end for;
    end for;
    quit;
else
    printf "\n ----------- FOR n = %o --------------\n\n", n;
    printf "Representatives : %o (computed in %o s)\n", #reps, t_reps;
    printf "Distances       : %o s, fast path for %o / %o codes\n\n",
           t_dist, nb_fast, nb_processed;
    print "Here is the list of all possible parameters,";
    print "with all non-equivalent representatives (under G):";
    print "";
    for p in sorted_keys do
        L := params[p];
        printf "- (%o, %o, %o) : %o representative(s)\n", p[1], p[2], p[3], #L;
        for c in L do
            printf "      A = %o,  B = %o\n",
                   SupportPolynomial(c[1], n), SupportPolynomial(c[2], n);
        end for;
    end for;
    print "";
end if;
